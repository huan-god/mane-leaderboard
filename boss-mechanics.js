export function resolveFlashbackStageMechanics(stage) {
  if (!stage) return null;
  const name = String(stage.name || '');
  const byName = FLASHBACK_STAGE_MECHANICS.find((item) => item.match.some((kw) => name.includes(kw)));
  if (byName) return byName;
  return FLASHBACK_STAGE_MECHANICS.find((item) => item.stageNo === Number(stage.stage_no)) || null;
}
